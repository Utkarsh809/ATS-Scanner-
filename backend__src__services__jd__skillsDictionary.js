// Canonical names that are also common English words or single letters ("Go", "Spring", "Excel"):
// these only match when written with the same capitalisation.
const CASE_SENSITIVE_CANONICAL = new Set([
  'C', 'R', 'Go', 'Swift', 'Rust', 'Ruby', 'Dart', 'Spring', 'Flask', 'Jest', 'Electron', 'Ionic', 'Looker', 'Excel', 'Assembly',
]);

/** A variant written as '=Text' is matched case-sensitively. */
function toVariant(text, forceCase) {
  if (text.startsWith('=')) return { text: text.slice(1), cs: true };
  return { text, cs: Boolean(forceCase) };
}

function buildDictionary() {
  return RAW.map(([canonical, category, ...aliases]) => ({
    canonical,
    category,
    variants: [toVariant(canonical, CASE_SENSITIVE_CANONICAL.has(canonical)), ...aliases.map((a) => toVariant(a))],
  }));
}

const DICTIONARY = buildDictionary();
const BY_CANONICAL = new Map(DICTIONARY.map((e) => [e.canonical.toLowerCase(), e]));

/** All spellings that count as a match for a canonical term (falls back to the term itself). */
function variantsFor(term) {
  const entry = BY_CANONICAL.get(String(term).toLowerCase());
  return entry ? entry.variants : [{ text: String(term), cs: false }];
}

module.exports = { DICTIONARY, QUALIFICATIONS, variantsFor };
